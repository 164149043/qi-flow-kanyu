/** 地理角（0=北，顺时针）→ 单位向量 {x,y}（canvas 坐标：0°朝上=北）。原站 dir2 同款。 */
export function dir2(bDeg) {
  const a = bDeg * Math.PI / 180;
  return { x: Math.sin(a), y: -Math.cos(a) };
}

