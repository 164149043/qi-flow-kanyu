/** 生成释义抽屉的出处块（有原文显引文，无原文仅标篇目） */
export function sourceBlock(key, extra) {
  const c = CLASSICS[key];
  if (!c) return '';
  return `<div class="src-block"><div class="src-book">出处 · ${c.book}</div>${c.quote ? `<blockquote class="src-quote">${c.quote}</blockquote>` : ''}<div class="src-note">${c.note}${extra || ''}</div></div>`;
}
